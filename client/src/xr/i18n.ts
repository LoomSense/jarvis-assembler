export type StringKey = keyof (typeof STRINGS)['en'];

export function t(key: StringKey, vars: Record<string, string | number> = {}, lang: Lang = LANG): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''));
}

