"""Helpers for part scripts.

Contract for a part script (hand-written or generated by the agent):

    PARAMS = {...}                       # all dimensions in mm
    def build(p) -> (cq.Workplane, dict) # the solid, and its named mate frames

A mate frame is a point on the part where another part or a fastener attaches:
    {"origin": [x, y, z], "axis": [ax, ay, az]}
`origin` lies on the part's surface. `axis` is a unit vector pointing OUT of the
material at that point (for a fastener: from the seat towards the tip).
Two frames mate when their origins coincide and their axes are opposite.
"""
from __future__ import annotations

import cadquery as cq


def frame(origin, axis) -> dict:
    n = sum(a * a for a in axis) ** 0.5
    return {"origin": [float(v) for v in origin], "axis": [float(a) / n for a in axis]}


def board(x0, y0, z0, dx, dy, dz, chamfer=0.8) -> cq.Workplane:
    """Axis-aligned board with its min corner at (x0, y0, z0). Edges are lightly
    chamfered so renders show the eased edges of real timber."""
    b = cq.Workplane("XY").box(dx, dy, dz, centered=False).translate((x0, y0, z0))
    if chamfer and min(dx, dy, dz) > 4 * chamfer:
        b = b.edges().chamfer(chamfer)
    return b


def drill(solid: cq.Workplane, origin, axis, diameter, depth) -> cq.Workplane:
    """Cut a round hole starting at `origin` on the surface and going INTO the
    material, i.e. along -axis (axis points out of the material)."""
    d = cq.Vector(*axis).normalized() * -1
    start = cq.Vector(*origin) - d * 0.5  # start slightly outside for a clean cut
    cutter = cq.Solid.makeCylinder(diameter / 2, depth + 0.5, start, d)
    return solid.cut(cq.Workplane(obj=cutter))


def union(*solids: cq.Workplane) -> cq.Workplane:
    out = solids[0]
    for s in solids[1:]:
        out = out.union(s)
    return out


def screw(length, shank_d, head_d, head_h, recess=True) -> cq.Workplane:
    """Pan-head screw. Seat (underside of head) at the origin, shank along +Z,
    head towards -Z. Threads are not modelled: they add triangles, not meaning."""
    shank = cq.Workplane("XY").circle(shank_d / 2).extrude(length - shank_d)
    tip = (cq.Workplane("XY").workplane(offset=length - shank_d)
           .circle(shank_d / 2).workplane(offset=shank_d).circle(0.3).loft())
    head = (cq.Workplane("XY").workplane(offset=-head_h).circle(head_d / 2 * 0.8)
            .workplane(offset=head_h).circle(head_d / 2).loft())
    s = union(shank, tip, head)
    if recess:  # cross recess
        for w, l in ((head_d * 0.14, head_d * 0.62), (head_d * 0.62, head_d * 0.14)):
            s = s.cut(cq.Workplane("XY").box(w, l, head_h, centered=(True, True, False))
                      .translate((0, 0, -head_h - 0.01 - head_h * 0.45)))
    return s
