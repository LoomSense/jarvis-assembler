#!/usr/bin/env python3
"""Write the printable tracking marker at true size on A4.

  .venv/bin/python tools/quest/marker/make_marker.py
  -> agj-marker-36h11-id0-80mm.pdf   vector, exact size (print at 100% / "Actual size")
  -> agj-marker-36h11-id0-80mm.png   300 dpi raster of the same page (dpi tag set)
  -> marker.json                     family, id, size and where it goes on the MALM drawer front

AprilTag 36h11 id 0: 8 x 8 modules of 10 mm including the black border = 80 mm black square,
inside a 100 mm white cut square (10 mm quiet zone).
"""
from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
NAME = "agj-marker-36h11-id0-80mm"
FAMILY, MID, SIZE_MM, CUT_MM = "apriltag_36h11", 0, 80.0, 100.0
A4 = (210.0, 297.0)
MX, MY = 105.0, 175.0                          # marker centre on the page, mm from bottom-left
PT = 72.0 / 25.4

PLACEMENT = {
    "part": "drawer_front (MALM drawer, 380 x 130 x 16 mm)",
    "face": "inside face: the face that is up in step 1, with the dowel holes and the groove for the drawer bottom",
    "position": "centred along the 380 mm length; centred across the 130 mm height between the groove and the "
                "opposite long edge (the 100 mm cut square fits; keep the groove and dowel holes clear)",
    "orientation": "the printed TOP edge of the marker points toward the groove edge; marker x runs along the "
                   "380 mm length, marker z points out of the inside face",
    "fixing": "flat, no bubbles: glue stick or low-tack spray; tape only on the white margin, never on the black",
    "visibility": "visible in steps 1-4 (front lying flat, sides going on); hidden once the bottom panel slides in. "
                  "Apps must hold the last good pose (anchor) when the marker is lost.",
}


def bits() -> np.ndarray:
    d = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_APRILTAG_36h11)
    return cv2.aruco.generateImageMarker(d, MID, 8, borderBits=1) > 0     # True = white module


def pdf_text(s: str) -> str:
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def make_pdf(b: np.ndarray, path: Path) -> None:
    mod = SIZE_MM / 8
    ops = ["q"]
    # Cut square (dashed, light grey) and corner marks.
    c0x, c0y = MX - CUT_MM / 2, MY - CUT_MM / 2
    ops += ["0.6 G 0.4 w [3 3] 0 d", f"{c0x * PT:.3f} {c0y * PT:.3f} {CUT_MM * PT:.3f} {CUT_MM * PT:.3f} re S", "[] 0 d"]
    # Black modules (row 0 of the image is the TOP of the marker).
    ops.append("0 g")
    left, top = MX - SIZE_MM / 2, MY + SIZE_MM / 2
    for r in range(8):
        for c in range(8):
            if not b[r, c]:
                x, y = left + c * mod, top - (r + 1) * mod
                ops.append(f"{x * PT:.4f} {y * PT:.4f} {mod * PT:.4f} {mod * PT:.4f} re")
    ops.append("f")      # one path, one fill (nonzero): no anti-aliasing seams between adjacent modules
    # Tiny TOP label inside the white margin, 7 mm above the black square.
    ops.append("0.55 g")
    ops.append(f"BT /F1 7 Tf {(MX - 4.2) * PT:.2f} {(MY + SIZE_MM / 2 + 6.0) * PT:.2f} Td ({pdf_text('TOP')}) Tj ET")
    # Ruler: 100 mm with 10 mm ticks.
    rx, ry = 55.0, 100.0
    ops += ["0 G 0.5 w", f"{rx * PT:.3f} {ry * PT:.3f} m {(rx + 100) * PT:.3f} {ry * PT:.3f} l S"]
    for k in range(11):
        h = 4.0 if k % 5 == 0 else 2.5
        ops.append(f"{(rx + 10 * k) * PT:.3f} {ry * PT:.3f} m {(rx + 10 * k) * PT:.3f} {(ry + h) * PT:.3f} l S")
    ops.append("0 g")
    texts = [
        (20, 280, 15, "F2", "Assembly Guide Agent: tracking marker"),
        (20, 271, 10, "F1", f"AprilTag 36h11, id {MID}. Black square {SIZE_MM:.0f} mm, cut square {CUT_MM:.0f} mm."),
        (20, 265, 10, "F1", "Print at 100% (\"Actual size\"), never \"Fit to page\". Check the ruler below."),
        (rx, ry - 6, 9, "F1", "This line must measure exactly 100 mm. If not, reprint."),
        (20, 80, 11, "F2", "Where it goes (MALM drawer)"),
        (20, 73, 9, "F1", "1. Cut along the dashed square. Keep the white margin: the tag needs it."),
        (20, 67, 9, "F1", "2. Drawer front, inside face (the face that is up in step 1, with the dowel holes"),
        (24, 62, 9, "F1", "and the groove for the drawer bottom)."),
        (20, 56, 9, "F1", "3. Centre it along the 380 mm length and between the groove and the other long edge."),
        (20, 50, 9, "F1", "4. TOP edge of the tag toward the groove. Glue it flat: no bubbles, no tape on black."),
        (20, 44, 9, "F1", "5. Visible in steps 1-4; the apps keep the last pose once the bottom panel covers it."),
        (20, 30, 8, "F1", "Generated by tools/quest/marker/make_marker.py. Spec: tools/quest/marker/marker.json."),
    ]
    for x, y, size, font, s in texts:
        ops.append(f"BT /{font} {size} Tf {x * PT:.2f} {y * PT:.2f} Td ({pdf_text(s)}) Tj ET")
    ops.append("Q")
    stream = "\n".join(ops).encode("latin-1")
    W, H = A4[0] * PT, A4[1] * PT
    objs = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {W:.3f} {H:.3f}] /Contents 4 0 R "
        f"/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> >>".encode(),
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    ]
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, o in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + o + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += b"".join(f"{o:010d} 00000 n \n".encode() for o in offsets)
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    path.write_bytes(bytes(out))


def make_png(b: np.ndarray, path: Path, dpi: int = 300) -> None:
    px = dpi / 25.4
    W, H = round(A4[0] * px), round(A4[1] * px)
    im = Image.new("L", (W, H), 255)
    d = ImageDraw.Draw(im)

    def xy(x_mm, y_mm):              # bottom-left mm -> top-left px
        return x_mm * px, (A4[1] - y_mm) * px
    mod = SIZE_MM / 8
    left, top = MX - SIZE_MM / 2, MY + SIZE_MM / 2
    for r in range(8):
        for c in range(8):
            if not b[r, c]:
                x0, y0 = xy(left + c * mod, top - r * mod)
                x1, y1 = xy(left + (c + 1) * mod, top - (r + 1) * mod)
                d.rectangle([round(x0), round(y0), round(x1) - 1, round(y1) - 1], fill=0)
    cx0, cy0 = xy(MX - CUT_MM / 2, MY + CUT_MM / 2)
    cx1, cy1 = xy(MX + CUT_MM / 2, MY - CUT_MM / 2)
    for k in range(0, int(cx1 - cx0), 24):     # dashed cut square
        d.line([cx0 + k, cy0, min(cx0 + k + 12, cx1), cy0], fill=150, width=2)
        d.line([cx0 + k, cy1, min(cx0 + k + 12, cx1), cy1], fill=150, width=2)
        d.line([cx0, cy0 + k, cx0, min(cy0 + k + 12, cy1)], fill=150, width=2)
        d.line([cx1, cy0 + k, cx1, min(cy0 + k + 12, cy1)], fill=150, width=2)
    rx, ry = 55.0, 100.0
    d.line([xy(rx, ry), xy(rx + 100, ry)], fill=0, width=3)
    for k in range(11):
        h = 4.0 if k % 5 == 0 else 2.5
        d.line([xy(rx + 10 * k, ry), xy(rx + 10 * k, ry + h)], fill=0, width=3)
    try:
        f_big, f, f_small = (ImageFont.load_default(size=s) for s in (60, 40, 30))
    except TypeError:
        f_big = f = f_small = ImageFont.load_default()
    d.text(xy(MX - 4.2, MY + SIZE_MM / 2 + 8.5), "TOP", fill=140, font=f_small)
    d.text(xy(20, 285), "Assembly Guide Agent: tracking marker", fill=0, font=f_big)
    d.text(xy(20, 274), f"AprilTag 36h11, id {MID}. Black square {SIZE_MM:.0f} mm. Print at 100%, check the ruler.",
           fill=0, font=f)
    d.text(xy(rx, ry - 3), "This line must measure exactly 100 mm.", fill=0, font=f)
    d.text(xy(20, 82), "Drawer front, inside face, centred; TOP edge toward the groove for the drawer bottom.",
           fill=0, font=f)
    im.save(path, dpi=(dpi, dpi))


def main() -> None:
    b = bits()
    make_pdf(b, HERE / f"{NAME}.pdf")
    make_png(b, HERE / f"{NAME}.png")
    (HERE / "marker.json").write_text(json.dumps({
        "family": FAMILY, "opencv_dictionary": "DICT_APRILTAG_36h11", "id": MID,
        "size_m": SIZE_MM / 1000, "size_note": "edge of the black square (8 x 8 modules of 10 mm incl. black border)",
        "cut_square_m": CUT_MM / 1000,
        "marker_axes": "OpenCV ArUco: x to the tag's right, y to its TOP edge, z out of the printed face; origin at the centre",
        "placement": PLACEMENT,
        "files": [f"{NAME}.pdf", f"{NAME}.png"],
    }, indent=2))
    print(f"wrote {NAME}.pdf, {NAME}.png, marker.json in {HERE}")


if __name__ == "__main__":
    main()
